import { chromium } from 'playwright-core';
const EXEC='/Users/aleksa/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const browser=await chromium.launch({executablePath:EXEC,headless:true});
const page=await browser.newPage({viewport:{width:393,height:852},deviceScaleFactor:2,isMobile:true,hasTouch:true});
const errs=[]; const failed=[];
page.on('pageerror',e=>errs.push(e.message));
page.on('console',m=>m.type()==='error'&&errs.push(m.text()));
page.on('requestfailed',r=>failed.push(r.url()));
page.on('response',r=>{ if(r.status()>=400) failed.push(`${r.status()} ${r.url()}`); });
await page.goto('http://127.0.0.1:4174/ironhold/',{waitUntil:'networkidle'});
await page.waitForTimeout(2500);
console.log('menu rendered:', await page.getByText('IRONHOLD',{exact:true}).count()>0);
console.log('playable:', await page.getByText('ENTER THE HOLD').count()>0);
console.log('failed requests:', failed.length? failed.slice(0,4).join(' | '):'none');
console.log('errors:', errs.length? errs.slice(0,3).join(' | '):'none');
await page.getByText('ENTER THE HOLD').click();
await page.waitForTimeout(2500);
console.log('world boots:', await page.evaluate(()=>document.querySelectorAll('svg').length>5));
await browser.close();
